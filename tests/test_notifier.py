"""Тесты без сети: форматирование, склейка серий, дубли, порог, задержка."""
import notifier as n

WALLET = "0x2005d16a84ceefa912d4e380cd32e7ff827875ea"


class FakeTelegram:
    def __init__(self):
        self.sent, self.edited = [], []

    def send(self, chat_id, text, buttons=None):
        self.sent.append((chat_id, text))
        return {"message_id": len(self.sent)}

    def edit(self, chat_id, message_id, text, buttons=None):
        self.edited.append((chat_id, message_id, text))


class FakeWatch:
    since = {WALLET: 0}


class FakePanel:
    def receivers(self):
        return [42]


def trade(tx="0x1", size=100.0, price=0.5, side="BUY", ts=1000, **extra):
    return {"proxyWallet": WALLET, "transactionHash": tx, "asset": "123", "side": side,
            "size": size, "price": price, "timestamp": ts, "name": "RN1",
            "title": "Will it rain?", "slug": "rain", "eventSlug": "weather",
            "outcome": "Yes", **extra}


def make(min_usdc=0, delay=0):
    tg = FakeTelegram()
    bot = n.Notifier(tg, api=None, watch=FakeWatch(), panel=FakePanel(), min_usdc=min_usdc,
                     group_seconds=3, merge_minutes=10, delay_seconds=delay)
    return bot, tg


def flush_later(bot, seconds):
    """Прогоняет отправку так, будто с последней сделки прошло seconds секунд."""
    bot.flush_once(max(b["at"] for b in bot.pending.values()) + seconds)


# -- форматирование -------------------------------------------------------
def test_nickname_skips_autogenerated_names():
    assert n.nickname({"name": "RN1"}) == "RN1"
    auto = "0xF5e47CaF8B2E23aa9230D70758bDb2c9747F471a-1746012744983"
    assert n.nickname({"name": auto, "pseudonym": "Devoted-Route"}) == "Devoted-Route"


def test_market_url_with_and_without_event():
    assert n.market_url({"eventSlug": "e", "slug": "m"}) == "https://polymarket.com/event/e/m"
    assert n.market_url({"eventSlug": "m", "slug": "m"}) == "https://polymarket.com/event/m"


def test_plural():
    assert [n.plural(x, "сделка", "сделки", "сделок") for x in (1, 3, 5, 11, 21, 22)] == \
        ["сделка", "сделки", "сделок", "сделок", "сделка", "сделки"]


def test_format_trade_links_and_amount():
    text = n.format_trade({"trade": trade(), "shares": 200, "usdc": 100,
                           "fills": 1, "first": 0, "last": 0})
    assert "🟢 ПОКУПКА" in text
    assert f"https://polymarket.com/profile/{WALLET}" in text
    assert "$100.00" in text and "50.0¢" in text and "«Yes»" in text
    assert "https://polymarket.com/event/weather/rain" in text


def test_format_trade_without_market_has_no_broken_link():
    t = trade(title="", slug="", eventSlug="")
    text = n.format_trade({"trade": t, "shares": 1, "usdc": 1, "fills": 1, "first": 0, "last": 0})
    assert "/event/" not in text


# -- склейка и отправка -----------------------------------------------------
def test_series_is_one_message_then_edits():
    bot, tg = make()
    bot.on_trade(trade(tx="0x1"))
    flush_later(bot, 3)
    bot.on_trade(trade(tx="0x2"))
    bot.on_trade(trade(tx="0x3"))
    flush_later(bot, 3)
    assert len(tg.sent) == 1
    assert len(tg.edited) == 1
    assert "$150.00" in tg.edited[-1][2] and "3 сделки" in tg.edited[-1][2]


def test_duplicate_fill_from_stream_and_poll_counted_once():
    bot, tg = make()
    bot.on_trade(trade())
    bot.on_trade(trade())
    flush_later(bot, 3)
    assert "$50.00" in tg.sent[0][1]


def test_buy_and_sell_are_separate_series():
    bot, tg = make()
    bot.on_trade(trade(side="BUY"))
    bot.on_trade(trade(tx="0x2", side="SELL"))
    flush_later(bot, 3)
    assert len(tg.sent) == 2


def test_min_usdc_waits_until_series_is_big_enough():
    bot, tg = make(min_usdc=100)
    bot.on_trade(trade(tx="0x1"))            # $50
    flush_later(bot, 3)
    assert tg.sent == []
    bot.on_trade(trade(tx="0x2"))            # итого $100
    flush_later(bot, 3)
    assert len(tg.sent) == 1 and "$100.00" in tg.sent[0][1]


def test_unknown_wallet_and_old_trades_ignored():
    bot, _ = make()
    bot.on_trade(trade(proxyWallet="0x" + "1" * 40))
    FakeWatch.since[WALLET] = 2000
    bot.on_trade(trade(ts=1000))
    FakeWatch.since[WALLET] = 0
    assert bot.pending == {}


def test_delay_postpones_signal():
    bot, tg = make(delay=2)
    bot.on_trade(trade())
    flush_later(bot, 3)
    assert tg.sent == []
    flush_later(bot, 5)
    assert len(tg.sent) == 1


def test_watchlist_parses_addresses_and_profile_links(tmp_path):
    w = n.Watchlist(tmp_path / "wallets.txt", api=None)
    assert w.parse(WALLET.upper().replace("0X", "0x")) == WALLET
    assert w.parse(f"https://polymarket.com/profile/{WALLET}") == WALLET
